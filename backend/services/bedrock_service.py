class BedrockService:
    """Manages Amazon Bedrock Converse API invocation and structured JSON parsing."""

    def __init__(self, region_name: Optional[str] = None):
        self.region_name = region_name or os.environ.get("AWS_REGION", "us-east-1")
        self.model_id = os.environ.get("BEDROCK_MODEL_ID", DEFAULT_BEDROCK_MODEL)
        self._client = None

    def _get_client(self):
        if self._client is None:
            import boto3
            self._client = boto3.client("bedrock-runtime", region_name=self.region_name)
        return self._client

    def analyze_document(self, minimized_text: str) -> Dict[str, Any]:
        """Invokes Bedrock Converse API with structured JSON output enforcement."""
        prompt = ANALYSIS_USER_TEMPLATE.format(document_text=minimized_text[:8000])

        try:
            client = self._get_client()
            response = client.converse(
                modelId=self.model_id,
                messages=[
                    {
                        "role": "user",
                        "content": [{"text": prompt}]
                    }
                ],
                system=[{"text": ANALYSIS_SYSTEM_PROMPT}],
                inferenceConfig={
                    "maxTokens": 1200,
                    "temperature": 0.1,
                    "topP": 0.9,
                }
            )

            raw_text = response["output"]["message"]["content"][0]["text"]
            return self._parse_json_response(raw_text)

        except Exception as e:
            logger.warning(f"Bedrock invocation failed or offline ({e}). Using deterministic fallback parser.")
            return self._deterministic_fallback_analysis(minimized_text)

    def _parse_json_response(self, text: str) -> Dict[str, Any]:
        """Extracts JSON object from markdown code fences or raw text."""
        cleaned = text.strip()
        if "```json" in cleaned:
            cleaned = cleaned.split("```json")[1].split("```")[0].strip()
        elif "```" in cleaned:
            cleaned = cleaned.split("```")[1].split("```")[0].strip()

        start = cleaned.find("{")
        end = cleaned.rfind("}")
        if start != -1 and end != -1:
            cleaned = cleaned[start:end+1]

        return json.loads(cleaned)

