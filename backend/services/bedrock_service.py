def analyze_document_with_bedrock(
    document_text: str,
    document_type: str = "lab_result",
    user_notes: str = "",
) -> List[Dict[str, Any]]:
    """Helper function that invokes Bedrock and maps findings to frontend-compatible finding dicts."""
    service = BedrockService()
    result = service.analyze_document(document_text)
    raw_insights = result.get("insights", [])

    formatted_findings = []
    for idx, ins in enumerate(raw_insights, start=1):
        finding_id = ins.get("id", f"f-{idx}")
        claim = ins.get("claim", "")
        explanation = ins.get("explanation", "")
        source = ins.get("source", {})
        source_quote = source.get("text", "")
        source_page = source.get("page", 1)

        formatted_findings.append({
            "id": finding_id,
            "title": ins.get("category", "Clinical Marker") + " — " + claim,
            "plainLanguageSummary": explanation,
            "clinicalSignificance": f"Value: {ins.get('value', '')} {ins.get('unit', '')} (Reference: {ins.get('referenceRange', '')})",
            "sourceQuote": source_quote,
            "sourcePage": source_page,
            "confidenceScore": 92 if ins.get("rangeStatus") == "outside_range" else 96,
            "verificationStatus": "verified" if ins.get("verification", {}).get("status") == "consistent" else "needs_review",
            "suggestedQuestionsForDoctor": [
                f"What does this {ins.get('category', 'test')} result mean for my health plan?",
                "Are follow-up tests recommended to recheck this biomarker?",
            ],
        })

    return formatted_findings
